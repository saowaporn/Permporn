function protectText(text){
  // An email address may wrap at punctuation; Thai words may not break inside.
  return text.split(/([A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,})/g).map((part,index)=>index%2?`<span class="text-address" lang="en">${part}</span>`:part.replace(wordPattern,word=>`<span class="thai-word">${word}</span>`).replace(/\b\d+(?:[.,]\d+)?[ \t]+(?:MB|KB|GB|THB|ct|กะรัต|มิลลิเมตร|บาท|รูป|วัน|ปี)(?![A-Za-z])/g,unit=>`<span class="thai-word">${unit}</span>`)).join('');
}
function formatThaiHtml(html){
  html=html.replace(/<(h[1-3])\b([^>]*)>([\s\S]*?)<\/\1>/g,(all,tag,attributes,content)=>{
    const formatted=content.replace(/<span class="lang-th" lang="th">([^<]*)<\/span>/g,(span,text)=>{
      const phrases=headingPhrases.get(text);
      return phrases?`<span class="lang-th" lang="th">${phrases.map(phrase=>phrase.trim()?`<span class="thai-phrase">${escape(phrase)}</span>`:phrase).join('<wbr>')}</span>`:span;
    });
    return `<${tag}${attributes}>${formatted}</${tag}>`;
  });
  // Leave metadata, user-editable controls, scripts and native options as text.
  return html.replace(/(<(?:script|style|textarea|option|title)\b[^>]*>[\s\S]*?<\/(?:script|style|textarea|option|title)>|<!--[\s\S]*?-->|<[^>]+>)|([^<]+)/gi,(_,markup,text)=>markup||protectText(text));
}
